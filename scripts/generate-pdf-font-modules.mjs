#!/usr/bin/env node
/**
 * Regenerates the base64-inlined font modules under
 * src/lib/exports/fonts/ from the canonical Amiri TTF files in
 * assets/fonts/amiri/ (see assets/fonts/amiri/SOURCE.md for provenance).
 *
 * Why inline base64 JS modules instead of reading the .ttf files from disk
 * at request time: this is jsPDF's own officially documented pattern for
 * custom fonts (its "Add Custom Fonts" tool generates exactly this shape —
 * a JS module exporting the font as base64, registered via
 * addFileToVFS/addFont). Baking the bytes into a normal `import`ed TS module
 * means the font ships as part of the ordinary JS bundle: no
 * `process.cwd()`-relative filesystem read that can break depending on
 * where a Vercel/Next serverless function's working directory ends up, no
 * dependency on Next's file-tracer noticing a `fs.readFileSync` call, and no
 * runtime network fetch.
 *
 * Run with: node scripts/generate-pdf-font-modules.mjs
 * Re-run this whenever assets/fonts/amiri/*.ttf changes (and update
 * assets/fonts/amiri/SOURCE.md's checksums to match).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const FONT_DIR = path.join(ROOT, 'assets', 'fonts', 'amiri');
const OUT_DIR = path.join(ROOT, 'src', 'lib', 'exports', 'fonts');

const FONTS = [
  { file: 'Amiri-Regular.ttf', exportName: 'AMIRI_REGULAR_BASE64', out: 'amiri-regular-base64.ts' },
  { file: 'Amiri-Bold.ttf', exportName: 'AMIRI_BOLD_BASE64', out: 'amiri-bold-base64.ts' },
];

for (const font of FONTS) {
  const ttfPath = path.join(FONT_DIR, font.file);
  const bytes = readFileSync(ttfPath);
  const base64 = bytes.toString('base64');
  const sha256 = createHash('sha256').update(bytes).digest('hex');

  const banner = `/**
 * Auto-generated by scripts/generate-pdf-font-modules.mjs from
 * assets/fonts/amiri/${font.file} -- do not hand-edit.
 *
 * SHA-256 of the source .ttf this was generated from: ${sha256}
 * (must match assets/fonts/amiri/SOURCE.md and the constant asserted
 * against it in src/lib/exports/pdf-fonts.ts).
 */\n`;

  const body = `export const ${font.exportName} = ${JSON.stringify(base64)};\n`;

  writeFileSync(path.join(OUT_DIR, font.out), banner + body, 'utf8');
  console.log(`wrote ${font.out} (${bytes.length} bytes source, sha256 ${sha256})`);
}
